// wavHeaderSize is the RIFF/WAV header an exported audio track begins with.
const wavHeaderSize = 44

// userDataSlice returns the [offset, offset+size) byte range of user data
// within a single raw sector for the given track mode.
//
// Both raw modes carry their data straight after the 16-byte sync and header. A
// MODE1 sector uses its last 288 bytes for EDC and ECC, leaving 2048 bytes of
// user data. A MODE2 sector, as a cue sheet defines it, has no such trailer, so
// all 2336 remaining bytes are user data, subheader included. Offset 24 is
// where Mode 2 Form 1's 2048-byte payload starts, and reading 2336 bytes from
// there would run off the end of the sector.
func userDataSlice(mode string) (offset, size int, err error) {
	switch strings.ToUpper(mode) {
	case "MODE1/2352":
		return 16, 2048, nil
	case "MODE2/2352", "CDI/2352":
		return 16, 2336, nil
	case "MODE1/2048", "MODE2/2048":
		// The whole sector in the file is already user data.
		return 0, cdrom.DataSectorSize, nil
	case "MODE2/2336", "CDI/2336":
		return 0, 2336, nil
	case "MODE2/2324":
		return 0, 2324, nil
	}
	// Guessing (0, 2048) for an unfamiliar mode would silently drift 16 bytes
	// per sector on a legal MODE2/2336 cue.
	return 0, 0, fmt.Errorf("cuebin: cannot export a track in mode %q", mode)
}

// ExtractDataTrack writes the user data of sectors [startLBA, endLBA) to w,
// stripping the sector headers for the given mode, and returns the map of the
// exported file's own bytes.
//
// The bytes are read unchecked and the holes are taken from blocks rather than
// from failed reads. Export writes finished artifacts: a strict reader would
// produce no ISO at all for a damaged disc, which is worse than an ISO whose
// zeros are recorded in its map. Zeroing also normalizes a BIN filled by GNU
// ddrescue --fill, whose holes hold whatever the fill left, so the exported
// file's bytes agree with its own map.
//
// A read short of a whole sector means the BIN is truncated. That is a
// different fault from a range the rescue never recovered (the export would
// simply be missing bytes), so it is reported rather than filled.
func ExtractDataTrack(ra io.ReaderAt, blocks []ddrescue.Block, startLBA, endLBA int64, mode string, binSectorSize int, w io.Writer) (*TrackMap, error) {
	uOff, uSize, err := userDataSlice(mode)
	if err != nil {
		return nil, err
	}
	tm := newTrackMap(blocks, int64(uSize))
	buf := make([]byte, binSectorSize)

	for lba := startLBA; lba < endLBA; lba++ {
		inOff := lba * int64(binSectorSize)
		if _, err := ra.ReadAt(buf, inOff); err != nil {
			return tm, fmt.Errorf("cuebin: read sector %d: %w", lba, err)
		}
		payload := buf[uOff : uOff+uSize]
		outOff := (lba - startLBA) * int64(uSize)
		// Only the user-data slice is checked. If a sector's payload was
		// recovered but its ECC was not, the payload is real data and the map
		// should mark it finished: the exported file does not carry the ECC, so
		// its loss says nothing about the bytes that are there.
		for _, b := range unrecovered(blocks, inOff+int64(uOff), int64(uSize)) {
			rel := b.Offset - (inOff + int64(uOff))
			clear(payload[rel : rel+b.Size])
			tm.fail(outOff+rel, b.Size)
		}
		tm.done(outOff + int64(uSize))
		if _, err := w.Write(payload); err != nil {
			return tm, fmt.Errorf("cuebin: write sector %d: %w", lba, err)
		}
	}
	return tm, nil
}

// ExtractAudioTrack writes sectors [startLBA, endLBA) to w as a WAV file, and
// returns the map of the exported file's own bytes. Set swapBytes for a
// big-endian source.
func ExtractAudioTrack(ra io.ReaderAt, blocks []ddrescue.Block, startLBA, endLBA int64, binSectorSize int, swapBytes bool, w io.Writer) (*TrackMap, error) {
	numSectors := endLBA - startLBA
	dataSize := numSectors * int64(binSectorSize)

	if err := writeWAVHeader(w, dataSize); err != nil {
		return nil, err
	}
	tm := newTrackMap(blocks, int64(binSectorSize))
	// The header is generated by this tool, not read from the disc, so it is
	// always marked recovered.
	tm.done(wavHeaderSize)

	buf := make([]byte, binSectorSize)
	for lba := startLBA; lba < endLBA; lba++ {
		inOff := lba * int64(binSectorSize)
		if _, err := ra.ReadAt(buf, inOff); err != nil {
			return tm, fmt.Errorf("cuebin: read audio sector %d: %w", lba, err)
		}
		outOff := wavHeaderSize + (lba-startLBA)*int64(binSectorSize)
		for _, b := range unrecovered(blocks, inOff, int64(binSectorSize)) {
			rel := b.Offset - inOff
			clear(buf[rel : rel+b.Size])
			start, end := rel, rel+b.Size
			if swapBytes {
				// Swapping moves each byte to the other half of its 2-byte
				// sample, so a hole starting or ending mid-sample would leave a
				// real byte where the map says lost. Round outward, since
				// marking a recovered byte lost is the safe direction.
				start &^= 1
				end = (end + 1) &^ 1
			}
			tm.fail(outOff+start, end-start)
		}
		if swapBytes {
			for i := 0; i+1 < len(buf); i += 2 {
				buf[i], buf[i+1] = buf[i+1], buf[i]
			}
		}
		tm.done(outOff + int64(binSectorSize))
		if _, err := w.Write(buf); err != nil {
			return tm, fmt.Errorf("cuebin: write audio sector %d: %w", lba, err)
		}
	}
	return tm, nil
}

// writeWAVHeader writes a 44-byte RIFF/WAV header for CD audio (44.1 kHz, 16-bit stereo).
func writeWAVHeader(w io.Writer, dataSize int64) error {
	const (
		sampleRate    = 44100
		numChannels   = 2
		bitsPerSample = 16
		blockAlign    = numChannels * bitsPerSample / 8
		byteRate      = sampleRate * blockAlign
	)
	// The RIFF and data size fields are 32-bit, so a track larger than 4 GiB
	// cannot be described; writing a wrapped length would produce a WAV whose
	// header disagrees with its contents.
	if dataSize < 0 || dataSize > math.MaxUint32-36 {
		return fmt.Errorf("cuebin: audio track of %d bytes does not fit a WAV header", dataSize)
	}
	header := make([]byte, wavHeaderSize)
	copy(header[0:4], "RIFF")
	binary.LittleEndian.PutUint32(header[4:8], uint32(36+dataSize))
	copy(header[8:12], "WAVE")
	copy(header[12:16], "fmt ")
	binary.LittleEndian.PutUint32(header[16:20], 16) // PCM chunk size
	binary.LittleEndian.PutUint16(header[20:22], 1)  // PCM format
	binary.LittleEndian.PutUint16(header[22:24], numChannels)
	binary.LittleEndian.PutUint32(header[24:28], sampleRate)
	binary.LittleEndian.PutUint32(header[28:32], byteRate)
	binary.LittleEndian.PutUint16(header[32:34], blockAlign)
	binary.LittleEndian.PutUint16(header[34:36], bitsPerSample)
	copy(header[36:40], "data")
	binary.LittleEndian.PutUint32(header[40:44], uint32(dataSize))
	_, err := w.Write(header)
	return err
}

// BinPath resolves the bin filename to an absolute path relative to the cue file.
func BinPath(cuePath, binName string) string {
	if filepath.IsAbs(binName) {
		return binName
	}
	return filepath.Join(filepath.Dir(cuePath), binName)
}
